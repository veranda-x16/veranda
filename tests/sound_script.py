#!/usr/bin/env python3
"""Gate sound (tools/gate_sound.sh, DECISIONS V69): tests/sound.s's scripts.

usage: sound_script.py gate|wav <steps.inc>

gate: every sound at the default settings (SND_MENU silent: the menu ticks
      are off), Beep; the menu ticks on; the volume at 32 and 0 (the
      alarm at its own), and byte 15 as blocks saved before V72 have it (full
      volume); the sounds off with a sentinel in voices 14 and
      15 (nothing written, but the alarm); a sound replacing another, the
      alarm not replaced, the alarm again.
wav:  the WAV recording on, then every sound (the menu ticks on) with 50
      frames of silence after each, for tools/gate_sound.sh to cut.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'tools'))
import mksounds  # noqa: E402

OP_PLAY, OP_BEEP, OP_PREFS, OP_SENT, OP_WAIT, OP_WAV, OP_END = range(1, 8)
IDS = mksounds.api_ids()
N = len(mksounds.SOUNDS)
WAV_GAP = 50
VOLSET = 0x80                   # PREFS_VOLSET (V72)


def wait(n):
    out = []
    while n > 0:
        out.append(('wait', min(n, 255)))
        n -= 255
    return out


def play(sid, gap=None):
    return [('play', sid)] + wait(mksounds.frames(sid) + 8 if gap is None else gap)


def script(kind):
    s = wait(30)
    if kind == 'wav':
        s += [('prefs', 0x40, 0), ('wav',)] + wait(10)
        for sid in range(1, N + 1):
            s += play(sid, mksounds.frames(sid) + WAV_GAP)
        return s + [('end',)]
    for sid in range(1, N + 1):                 # the defaults
        s += play(sid, None if sid != IDS['MENU'] else 10)
    s += [('beep',)] + wait(mksounds.frames(IDS['ERROR']) + 8)
    s += [('prefs', 0x40, 0)] + wait(4) + play(IDS['MENU'])
    s += [('prefs', 0, VOLSET | 63 - 31)] + wait(4) + play(IDS['STARTUP']) + play(IDS['TRASH']) + play(IDS['ALARM'])
    s += [('prefs', 0, VOLSET | 63)] + wait(4) + play(IDS['WARNING'])
    # blocks saved before V72: byte 15 as V56's and V65's Preferences left it
    # (0, the kernel's default: the user's file), and as V69's wrote a volume
    # of 31 (32, no PREFS_VOLSET): full volume both
    s += [('prefs', 0, 0)] + wait(4) + play(IDS['STARTUP'])
    s += [('prefs', 0, 63 - 31)] + wait(4) + play(IDS['STARTUP'])
    s += [('prefs', 0xC0, 0)] + wait(4) + [('sent',)] + wait(4)
    for sid in range(1, N + 1):                 # the sounds off
        if sid != IDS['ALARM']:
            s += play(sid, 6)
    s += [('beep',)] + wait(6) + play(IDS['ALARM'])
    s += [('prefs', 0, 0)] + wait(4)
    s += play(IDS['STARTUP'], 12) + play(IDS['ERROR'])          # replaced
    s += play(IDS['ALARM'], 10) + play(IDS['ERROR'], 10) + play(IDS['EXIT'], 10)    # not
    s += play(IDS['ALARM'], 20) + play(IDS['ALARM'])           # the alarm again
    return s + wait(10) + [('end',)]


def encode(steps):
    out = []
    for st in steps:
        k = st[0]
        if k == 'play':
            out += [OP_PLAY, st[1]]
        elif k == 'beep':
            out.append(OP_BEEP)
        elif k == 'prefs':
            out += [OP_PREFS, st[1], st[2]]
        elif k == 'sent':
            out.append(OP_SENT)
        elif k == 'wait':
            out += [OP_WAIT, st[1]]
        elif k == 'wav':
            out.append(OP_WAV)
        elif k == 'end':
            out.append(OP_END)
    return out


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in ('gate', 'wav'):
        sys.exit(__doc__)
    b = encode(script(sys.argv[1]))
    lines = ['; generated by tests/sound_script.py %s' % sys.argv[1]]
    for i in range(0, len(b), 16):
        lines.append('\t.byte ' + ', '.join(str(x) for x in b[i:i + 16]))
    open(sys.argv[2], 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
