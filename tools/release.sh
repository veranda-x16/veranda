#!/bin/bash
# A Veranda release, start to end (docs/RELEASING.md).
#
#   tools/release.sh [options] <version>          e.g. tools/release.sh 1.0
#
# From a clean main of this tree: the gates, the package (tools/mkdist.sh,
# the programs that were copied by hand included), its README's NEW IN
# THIS BUILD and hardware checklist, CHANGES.txt, UPDATE.LST with the
# version and what's new, the zip, the public release's folder
# (tools/mkrelease.sh: the allowlist, no port), veranda-x16's next patch
# (tools/mkx16patch.sh, built and gated in a clone), the local tag
# veranda-<version>, and a summary. It never pushes, never publishes and
# never writes to the SD card: the gh, git am and push steps are yours
# (printed at the end), and tools/tocard.sh copies the package to a card.
#
# Options:
#   --dry-run        any branch; VERSION not committed (VERANDA_VERSION is
#                    given to the build), no tag; everything else as for real
#   --no-gates       skip the gates (with --dry-run only)
#   --keep-going     go on after a gate failed twice (with --dry-run only)
#   --gates "a b"    only these gates (names as in the summary)
#   --x16            also veranda-x16's patch (the old public repository,
#                    sandlbn/veranda-x16: before the organisation, V139)
#   --no-x16         no veranda-x16 patch (the default since V139)
#   --notes-only     write the draft "what's new" and stop
#
# Environment:
#   DIST=~/Projects/veranda-dist   where the results go: pkg-<version>-<hash>/,
#                                  veranda-<version>-<date>-<hash>.zip,
#                                  rel-<version>-<hash>/, patches/veranda-x16/,
#                                  release-<version>-<hash>.log
#   PREV=<commit>                  the release before (default: the newest
#                                  tag veranda-*, else the build of the newest
#                                  $PKGS/pkg-*/VERANDA/UPDATE.LST; PKGS
#                                  defaults to ~/Projects/veranda-dist)
#   NOTES=<file>                   what's new, one "- " line a point (default:
#                                  docs/releases/<version>.txt if the tree has
#                                  it, else generated by tools/relnotes.py)
#   CHANNEL=stable|test            the GitHub channel (tools/mkrelease.py)
#   TILEHW=<dir>                   the tile test carried into the package
#                                  (default ~/Projects/veranda-dist/tiletrial/
#                                  TILEHW: its source is not in any tree;
#                                  TILEHW= leaves it out)
#   X16, PATCHES, X16_BASE, X16_GATES   tools/mkx16patch.sh's
set -e
cd "$(dirname "$0")/.."
TOP=$PWD
DRY=0 GATES_ON=1 ONLY_GATES="" X16_ON=0 NOTES_ONLY=0 KEEP=0
while [ $# -gt 0 ]; do
	case $1 in
	--dry-run) DRY=1 ;;
	--no-gates) GATES_ON=0 ;;
	--keep-going) KEEP=1 ;;
	--gates) shift; ONLY_GATES=$1 ;;
	--no-x16) X16_ON=0 ;;
	--x16) X16_ON=1 ;;
	--notes-only) NOTES_ONLY=1 ;;
	-*) echo "release: unknown option $1" >&2; exit 2 ;;
	*) break ;;
	esac
	shift
done
VER=$1
[ -n "$VER" ] || { sed -n '2,40p' "$0" | sed 's/^# \{0,1\}//'; exit 2; }
DIST=${DIST:-$HOME/Projects/veranda-dist}
CHANNEL=${CHANNEL:-stable}
TILEHW=${TILEHW-$HOME/Projects/veranda-dist/tiletrial/TILEHW}
PY="python3 -I -B"
T0=$(date +%s)
say() { echo "release: $*"; }
die() { echo "release: STOPPED: $*" >&2; exit 1; }

# ---------------------------------------------------------------- checks
echo "$VER" | grep -qE '^[0-9]{1,3}\.[0-9]{1,3}(\.[0-9]{1,3})?(-[0-9A-Za-z]{1,6})?$' || die "version $VER: N.M or N.M.P (or 1.0.1-rc1)"
[ "$GATES_ON" = 1 ] || [ "$DRY" = 1 ] || die "--no-gates only with --dry-run"
[ "$KEEP" = 0 ] || [ "$DRY" = 1 ] || die "--keep-going only with --dry-run"
[ -z "$(git status --porcelain)" ] || die "this tree is not clean (git status)"
BR=$(git rev-parse --abbrev-ref HEAD)
if [ "$BR" != main ]; then
	[ "$DRY" = 1 ] || die "on $BR: a release is made from main (--dry-run for a try)"
	say "WARNING: on $BR, not main (a dry run)"
fi
TAG=veranda-$VER
if git rev-parse -q --verify "refs/tags/$TAG" >/dev/null; then
	die "the tag $TAG is there already (git tag -d $TAG to make it again)"
fi
# the release before: the newest tag veranda-*, else the newest package
# (PKGS: where the packages are) whose build this branch has
PKGS=${PKGS:-$HOME/Projects/veranda-dist}
if [ -z "$PREV" ]; then
	PREVTAG=$(git tag -l 'veranda-[0-9]*' --merged HEAD --sort=-v:refname | head -1)
	PREV=$PREVTAG
fi
if [ -z "$PREVTAG" ]; then
	for d in $(ls -td "$PKGS"/pkg-* 2>/dev/null); do
		b=$(sed -n 's/^build \([0-9a-f]*\) .*/\1/p' "$d/VERANDA/UPDATE.LST" 2>/dev/null)
		[ -n "$b" ] && git merge-base --is-ancestor "$b" HEAD 2>/dev/null || continue
		if [ -z "$PREV" ] || [ "$(git rev-parse "$b")" = "$(git rev-parse "$PREV^{commit}" 2>/dev/null)" ]; then
			PREV=${PREV:-$b} PREVPKG=$d
			break
		fi
	done
fi
[ -n "$PREV" ] || die "no release before (no tag veranda-*, no package in $DIST): PREV=<commit>"
git rev-parse -q --verify "$PREV^{commit}" >/dev/null || die "PREV $PREV: not a commit"
# ---------------------------------------------------------------- the version
if [ "$(cat VERSION 2>/dev/null)" != "$VER" ]; then
	if [ "$DRY" = 1 ]; then
		export VERANDA_VERSION=$VER
		say "VERSION says $(cat VERSION 2>/dev/null || echo nothing): built as $VER (VERANDA_VERSION), not committed"
	else
		echo "$VER" > VERSION
		git add VERSION
		git commit -q -m "Veranda $VER" -m "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>"
		say "VERSION: $VER, committed ($(git rev-parse --short HEAD))"
	fi
fi

HASH=$(git rev-parse --short HEAD)
DATE=$(date +%Y-%m-%d)
NAME=$VER-$HASH
W=$DIST/work-$NAME
PKG=$DIST/pkg-$NAME
ZIP=$DIST/veranda-$VER-$DATE-$HASH.zip
REL=$DIST/rel-$NAME
PATCHOUT=$DIST/patches/veranda-x16
LOG=$DIST/release-$NAME.log
for p in "$PKG" "$REL" "$ZIP" "$W"; do
	[ ! -e "$p" ] || die "$p is there already"
done
mkdir -p "$W"
exec > >(tee -a "$LOG") 2>&1
say "Veranda $VER from $BR $HASH ($DATE), since $(git rev-parse --short "$PREV")${PREVTAG:+ ($PREVTAG)}; results in $DIST"
# the sibling repositories: their committed refs are built (git archive),
# so a dirty tree is only a warning
P=${VERANDA_PROJECTS:-$HOME/Projects}   # (the sibling repositories' folder)
for r in veranda-geowrite commander-calc commander-write veranda-geochess x16-mod veranda-solitaire \
	veranda-pinball harbour-walls veranda-sidplay veranda-x16; do
	[ -d "$P/$r/.git" ] || { say "WARNING: no $P/$r"; continue; }
	[ -z "$(git -C "$P/$r" status --porcelain --untracked-files=no)" ] ||
		say "WARNING: $r has uncommitted changes (not in the build: its committed ref is)"
done

# ---------------------------------------------------------------- what's new
if [ -z "$NOTES" ] && [ -f "docs/releases/$VER.txt" ]; then
	NOTES=docs/releases/$VER.txt
fi
if [ -z "$NOTES" ]; then
	NOTES=$W/whatsnew.txt
	$PY tools/relnotes.py notes --since "$PREV" --version "$VER" -o "$NOTES"
	say "what's new: generated from DECISIONS and the commits since $(git rev-parse --short "$PREV") ($NOTES)"
else
	cp "$NOTES" "$W/whatsnew.txt"
	NOTES=$W/whatsnew.txt
	say "what's new: from $NOTES"
fi
sed 's/^/    /' "$NOTES" | grep -v '^    #'
if [ "$NOTES_ONLY" = 1 ]; then
	say "the draft is $NOTES: edit it, keep it as docs/releases/$VER.txt (committed) or pass NOTES=, then run again"
	exit 0
fi

# ---------------------------------------------------------------- the gates
GS=$W/gates.txt
: > "$GS"
FLAKY="" FAILED=""
gate_cmd() {            # a gate's name: its command
	case $1 in
	spec | boot | gfx1 | gfx | input | ui | disk) echo "tools/gate.sh $1" ;;
	*) echo "tools/gate_$1.sh" ;;
	esac
}
if [ "$GATES_ON" = 1 ]; then
	if [ -n "$ONLY_GATES" ]; then
		LIST=$ONLY_GATES
	else
		LIST="spec boot gfx1 gfx input ui disk $(ls tools/gate_*.sh | sed 's|tools/gate_\(.*\)\.sh|\1|' | tr '\n' ' ')"
	fi
	set -- $LIST
	say "the gates: $# ($(echo $LIST))"
	mkdir -p "$W/gates"
	for g in $LIST; do
		c=$(gate_cmd "$g")
		t=$(date +%s)
		res=FAIL
		for try in 1 2; do
			if timeout 1800 $c > "$W/gates/$g.$try.log" 2>&1; then
				res=PASS
				break
			fi
		done
		if [ $res = PASS ] && [ $try = 2 ]; then
			res=FLAKY
			FLAKY="$FLAKY $g"
		fi
		[ $res = FAIL ] && FAILED="$FAILED $g"
		printf '  %-14s %-6s %4ss  %s\n' "$g" "$res" "$(( $(date +%s) - t ))" \
			"$(grep -a -m1 'GATE\|^FAIL' "$W/gates/$g.$try.log" | cut -c1-60)" | tee -a "$GS"
	done
	say "gates: $(grep -c ' PASS ' "$GS") pass, $(grep -c ' FLAKY ' "$GS") flaky (passed the second time:$FLAKY), $(grep -c ' FAIL ' "$GS") fail$FAILED"
	if [ -n "$FAILED" ]; then
		[ "$KEEP" = 1 ] || die "the gates failed:$FAILED (logs in $W/gates)"
		say "WARNING: the gates failed:$FAILED (logs in $W/gates); going on (--keep-going, a dry run)"
	fi
else
	echo "  (the gates skipped: --no-gates)" > "$GS"
	say "the gates: skipped (--no-gates, a dry run)"
fi

# ---------------------------------------------------------------- the package
say "the package: tools/mkdist.sh $PKG"
MKDIST_WORK=$W/mkdist tools/mkdist.sh "$PKG" > "$W/mkdist.log" 2>&1 || { tail -20 "$W/mkdist.log"; die "mkdist.sh ($W/mkdist.log)"; }
grep '^mkdist: ' "$W/mkdist.log" | sed 's/^/  /'
grep -q 'WARNING' "$W/mkdist.log" && say "WARNING: mkdist left something out (above)"
for f in "Lighthouse Pinball" "Harbour Walls" "SID Player"; do
	[ -f "$PKG/VERANDA/APPS/$f.cvt" ] || die "$f.cvt is not in the package (its sibling repository: tools/mkdist.sh)"
done
# carried over: the tile test (its source is in no repository)
if [ -n "$TILEHW" ]; then
	[ -f "$TILEHW/TILEHW.PRG" ] || die "no $TILEHW/TILEHW.PRG (TILEHW= leaves the tile test out)"
	mkdir -p "$PKG/TILEHW"
	cp "$TILEHW"/* "$PKG/TILEHW/"
	say "carried over: TILEHW ($(ls "$PKG/TILEHW" | wc -l) files from $TILEHW)"
fi
# the README's sections, CHANGES.txt
if [ -n "$PREVTAG" ]; then
	$PY tools/relnotes.py prevrefs --tag "$PREVTAG" -o "$W/prevrefs.txt"
elif [ -n "$PREVPKG" ]; then
	$PY tools/relnotes.py prevrefs --pkg "$PREVPKG" -o "$W/prevrefs.txt"
else
	echo "BUILT FROM" > "$W/prevrefs.txt"
fi
$PY tools/relnotes.py readme "$PKG" --version "$VER" --since "$PREV" --notes "$NOTES" \
	--checklist tools/checklist.txt --prev-refs "$W/prevrefs.txt" ${TILEHW:+--tilehw} > "$W/readme.out" 2>&1 ||
	{ cat "$W/readme.out"; die "relnotes.py readme"; }
sed 's/^/  /' "$W/readme.out"
# UPDATE.LST again: the README changed, CHANGES.txt is new; what's new
$PY tools/relnotes.py short --version "$VER" --notes "$NOTES" -o "$W/short.txt"
$PY tools/mkmanifest.py "$PKG" --build "$HASH" --date "$DATE" --version "$VER" --notes-file "$W/short.txt" \
	> "$W/manifest.out" 2>&1 || { cat "$W/manifest.out"; die "mkmanifest.py"; }
grep -v 'TILEHW/\|: VERANDA/UPDATE.LST$' "$W/manifest.out" | sed 's/^/  /' || true

# ---------------------------------------------------------------- the zip
(cd "$DIST" && zip -q -r -X "$ZIP" "$(basename "$PKG")") || die "zip"
say "the zip: $ZIP ($(du -h "$ZIP" | cut -f1))"

# ---------------------------------------------------------------- the public release
CHANNEL=$CHANNEL tools/mkrelease.sh "$PKG" "$REL" > "$W/mkrelease.log" 2>&1 || { cat "$W/mkrelease.log"; die "mkrelease.sh"; }
grep -v '^gh \|^#\|to publish it' "$W/mkrelease.log" | sed 's/^/  /'
GH=$(sed -n '/^gh \|^# /p' "$W/mkrelease.log")

# ---------------------------------------------------------------- veranda-x16
PATCHF=""
if [ "$X16_ON" = 1 ]; then
	say "veranda-x16's patch (tools/mkx16patch.sh)"
	NOTES=$NOTES tools/mkx16patch.sh "$W/x16" "$PATCHOUT" "$VER" > "$W/x16.log" 2>&1 ||
		{ sed 's/^/  /' "$W/x16.log"; die "mkx16patch.sh ($W/x16.log)"; }
	sed 's/^/  /' "$W/x16.log"
	PATCHF=$(cat "$W/x16/patch.txt" 2>/dev/null || true)
fi

# ---------------------------------------------------------------- the tag
$PY tools/relnotes.py tagmsg "$PKG" --version "$VER" --notes "$NOTES" -o "$W/tag.txt"
if [ "$DRY" = 1 ]; then
	say "a dry run: no tag (it would be $TAG on $HASH)"
else
	git tag -a "$TAG" -F "$W/tag.txt" HEAD
	say "tagged $TAG ($HASH), local only"
fi

# ---------------------------------------------------------------- the summary
cat <<EOF

================================================================ Veranda $VER
  version   $VER, build $HASH, $DATE (since $(git rev-parse --short "$PREV")${PREVTAG:+, $PREVTAG})$([ "$DRY" = 1 ] && echo "  [DRY RUN]")
  gates     $(grep -c ' PASS ' "$GS") pass, $(grep -c ' FLAKY ' "$GS") flaky${FLAKY:+ ($FLAKY )}, $(grep -c ' FAIL ' "$GS") fail$([ "$GATES_ON" = 1 ] || echo " (skipped)")
  package   $PKG
            $(find "$PKG" -type f | wc -l) files, $(du -sh "$PKG" | cut -f1); APPS: $(ls "$PKG/VERANDA/APPS" | wc -l) programs
  zip       $ZIP ($(du -h "$ZIP" | cut -f1))
  release   $REL ($CHANNEL): $(grep -c '^file ' "$REL/UPDATE.LST") files, $(ls "$REL" | grep -c '\.bin$') assets, $(du -sh "$REL" | cut -f1)
  patch     ${PATCHF:-(none: the veranda-x16 patch only with --x16)}
  log       $LOG
  work      $W

YOUR STEPS (nothing above was pushed or published):
  1. the hardware: tools/tocard.sh $PKG [<card>]
  2. publish (docs/PUBLISHING.md): tools/publish.sh --dry-run $VER, then
     tools/publish.sh $VER: the organisation's repositories, tag v$VER (its
     release workflow builds the GitHub release from the source), the wiki
  3. this tree: git push origin main $TAG   (if you keep a remote)
$(if [ -n "$PATCHF" ]; then
	echo "  (the old repository, --x16: git -C ${X16:-$HOME/Projects/veranda-x16} am $PATCHF, push, then:"
	echo "$GH" | sed 's/^/     /'
	echo "  )"
fi)
EOF
say "done in $(( ($(date +%s) - T0) / 60 )) min"
