#!/usr/bin/env python3
"""Veranda's system icons for dialog boxes (OK, Cancel, Yes, No, Open,
Disk): 48x16 pictures, a frame with rounded corners and the word in the
system font (tools/mkfont.py), in GEOS's compacted bitmap format; the
default buttons (OK, Yes, Open) with a frame two pixels thick (Veranda Look
3, Sunroom: DECISIONS V146).

usage: mkicons.py <out.inc> [--png out.png]

Writes ca65 source: IconOK, IconCancel, IconYes, IconNo, IconOpen, IconDisk.
The pictures are Veranda's own (MIT).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mkfont  # noqa: E402

W, H = 48, 16
NAMES = [('IconOK', 'OK'), ('IconCancel', 'Cancel'), ('IconYes', 'Yes'), ('IconNo', 'No'),
         ('IconOpen', 'Open'), ('IconDisk', 'Disk')]


DEFAULT = ('OK', 'Yes', 'Open')    # (V146, Sunroom) the default buttons: a double frame


def frame(px, i):
    """a frame inset i, its corners cut"""
    for x in range(i + 2, W - 2 - i):
        px[i][x] = px[H - 1 - i][x] = 1
    for y in range(i + 2, H - 2 - i):
        px[y][i] = px[y][W - 1 - i] = 1
    px[i + 1][i + 1] = px[i + 1][W - 2 - i] = px[H - 2 - i][i + 1] = px[H - 2 - i][W - 2 - i] = 1


def picture(word):
    px = [[0] * W for _ in range(H)]
    frame(px, 0)                                    # Sunroom (V146): a rounded frame;
    if word in DEFAULT:                             # the default's two pixels thick
        for x in range(2, W - 2):
            px[1][x] = px[H - 2][x] = 1
        for y in range(2, H - 2):
            px[y][1] = px[y][W - 2] = 1
    width = sum(len(mkfont.G[c][0]) for c in word) - 1
    x0, top = (W - width) // 2, 3
    for c in word:
        g = mkfont.G[c]
        for r in range(mkfont.H):
            for i, ch in enumerate(g[r]):
                if ch == '#' and top + r < H - 2:
                    px[top + r][x0 + i] = 1
        x0 += len(g[0])
    return px


def pack(px):
    """rows of bytes -> GEOS compacted: count < $80 repeats the next byte,
    $80 + n is n literal bytes"""
    data = [sum(px[y][x * 8 + b] << (7 - b) for b in range(8)) for y in range(H) for x in range(W // 8)]
    out, i = [], 0
    while i < len(data):
        j = i
        while j < len(data) and data[j] == data[i] and j - i < 127:
            j += 1
        if j - i >= 3:
            out += [j - i, data[i]]
            i = j
            continue
        k = i                                       # literals until a run of 3
        while k < len(data) and k - i < 91:
            if k + 2 < len(data) and data[k] == data[k + 1] == data[k + 2]:
                break
            k += 1
        out += [0x80 + k - i] + data[i:k]
        i = k
    return out


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    lines = ['; generated by tools/mkicons.py: the system icons, 6 cards by 16 rows']
    pics = []
    for label, word in NAMES:
        px = picture(word)
        pics.append(px)
        b = pack(px)
        lines.append('%s:' % label)
        for i in range(0, len(b), 16):
            lines.append('\t.byte ' + ', '.join('$%02X' % v for v in b[i:i + 16]))
    open(sys.argv[1], 'w').write('\n'.join(lines) + '\n')
    if '--png' in sys.argv:
        from PIL import Image
        img = Image.new('1', (W, (H + 4) * len(pics)), 1)
        for n, px in enumerate(pics):
            for y in range(H):
                for x in range(W):
                    if px[y][x]:
                        img.putpixel((x, n * (H + 4) + y), 0)
        img.resize((W * 4, (H + 4) * len(pics) * 4)).save(sys.argv[sys.argv.index('--png') + 1])


if __name__ == '__main__':
    main()
