#!/usr/bin/env python3
"""Split the generated C bindings (build/gen/veranda_c.s) into one source a
function, so that ar65's library gives a program only the calls it uses.

usage: splitc.py <veranda_c.s> <outdir>

Writes <outdir>/c_tmp.s (the shared scratch bytes tmp_a, tmp_x, tmp_y) and
<outdir>/c_<name>.s for every exported function.
"""
import os
import re
import sys


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    src, out = sys.argv[1:]
    os.makedirs(out, exist_ok=True)
    text = open(src).read()
    head, _, body = text.partition('.segment "CODE"')
    # the scratch bytes, once
    open(os.path.join(out, 'c_tmp.s'), 'w').write(
        '; generated by tools/splitc.py\n.export tmp_a, tmp_x, tmp_y\n.segment "BSS"\n'
        'tmp_a:\t.res 1\ntmp_x:\t.res 1\ntmp_y:\t.res 1\n')
    pre = '; generated by tools/splitc.py from %s\n.include "veranda.inc"\n.import popa, popax\n' \
          '.import tmp_a, tmp_x, tmp_y\n.segment "CODE"\n' % os.path.basename(src)
    blocks = re.split(r'\n(?=\.export _)', body)
    n = 0
    for b in blocks:
        m = re.match(r'\s*\.export (_\w+)', b)
        if not m:
            continue
        open(os.path.join(out, 'c%s.s' % m.group(1)), 'w').write(pre + b.strip() + '\n')
        n += 1
    if n == 0 or 'tmp_a:' not in head:
        sys.exit('splitc: unexpected layout of %s' % src)


if __name__ == '__main__':
    main()
