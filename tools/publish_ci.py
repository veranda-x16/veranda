#!/usr/bin/env python3
"""The CI workflow of a sibling repository (DECISIONS V139): written by
tools/publish.sh into each export as .github/workflows/veranda-ci.yml.

    publish_ci.py <repo>

On a push to main or next, a tag v*, a pull request or by hand: Veranda's
SDK is built from veranda-x16/veranda (the same tag or branch, else main)
with the pinned cc65 (tools/ci/setup.sh), then the repository's own build (tools/publish.repos: build, output) against it.
The build command and the output come from the map, so this file is the
one place to change them. MIT licence (see LICENSE)."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import publish  # noqa: E402

ACT = {
    'checkout': 'actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1  # v7.0.1',
    'cache': 'actions/cache@55cc8345863c7cc4c66a329aec7e433d2d1c52a9  # v6.1.0',
}

TEMPLATE = '''# Generated by Veranda's tools/publish_ci.py from tools/publish.repos
# (DECISIONS V139): change it there, not here; tools/publish.sh writes it.
name: build
on:
  push:
    branches: [main, next, veranda]
    tags: ['v*']
  pull_request:
  workflow_dispatch:
permissions:
  contents: read
jobs:
  build:
    runs-on: ubuntu-24.04
    timeout-minutes: 30
    steps:
      - uses: {checkout}
        with:
          path: app
      - name: Veranda's source (its SDK; the same tag or branch, else main)
        env:
          WANT: ${{{{ github.ref_name }}}}
        run: |
          # (publish.sh pushes the siblings' tags before veranda's: a tag's
          # build can come before Veranda has the tag, and then uses main)
          git clone -q https://github.com/veranda-x16/veranda.git veranda
          git -C veranda checkout -q "$WANT" 2>/dev/null || git -C veranda checkout -q main
          echo "Veranda at $(git -C veranda describe --tags --always)"
      - name: cc65 (pinned), cached
        uses: {cache}
        with:
          path: ~/ci-tools/cc65
          key: cc65-547d923
      - name: Tools
        run: |
          sudo apt-get update -qq && sudo apt-get install -y -qq python3-pil >/dev/null
          veranda/tools/ci/setup.sh cc65
      - name: Veranda's SDK
        working-directory: veranda
        run: |
          python3 -I -B tools/apigen.py api/veranda.api build/gen
          python3 -I -B tools/kbuild.py
          tools/mksdk.sh "$RUNNER_TEMP/sdk"
      - name: Build {repo}
        working-directory: app
        env:
          SDK: ${{{{ runner.temp }}}}/sdk
          VSDK: ${{{{ runner.temp }}}}/sdk
        run: |
          {build}
          test -f '{output}'
          ls -l '{output}'
'''


def main():
    if len(sys.argv) != 2:
        sys.exit('usage: publish_ci.py <repo>')
    rows = {r['repo']: r for r in publish.read_map()}
    r = rows.get(sys.argv[1])
    if not r or r['build'] == '-':
        sys.exit('publish_ci: %s has no build in tools/publish.repos' % sys.argv[1])
    if r['mode'] == 'own':
        sys.exit('publish_ci: %s keeps its own workflow (mode own in tools/publish.repos)' % sys.argv[1])
    sys.stdout.write(TEMPLATE.format(repo=r['repo'], build=r['build'].replace('$SDK', '"$SDK"').replace('$VSDK', '"$VSDK"'),
                                     output=r['output'], **ACT))


if __name__ == '__main__':
    main()
