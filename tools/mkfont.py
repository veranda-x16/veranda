def build(hi=None):
    """the record (the index of 97 words; 193 with hi, V141: 96 glyphs of
    $A0-$FF, rows of '#' and '.' with their gap)"""
    chars = [chr(c) for c in range(32, 128)]
    glyphs = [G[ch] for ch in chars] + (hi or [])
    pos, x = [], 0
    for g in glyphs:
        pos.append(x)
        x += len(g[0])
    pos.append(x)
    setw = (x + 7) // 8
    bitmap = bytearray(setw * H)
    for g, p in zip(glyphs, pos):
        for r, row in enumerate(g):
            for i, c in enumerate(row):
                if c == '#':
                    bit = p + i
                    bitmap[r * setw + bit // 8] |= 0x80 >> (bit % 8)
    hdr_len = 8
    index_off = hdr_len
    bitmap_off = index_off + 2 * len(pos)
    out = bytearray([BASELINE, setw & 255, setw >> 8, H, index_off & 255, index_off >> 8,
                     bitmap_off & 255, bitmap_off >> 8])
    for p in pos:
        out += bytes([p & 255, p >> 8])
    out += bitmap
    return bytes(out), pos


def high(ui=False):
    """the 96 glyphs of $A0-$FF in the system font's style (ui: the UI
    font's), rows of '#' and '.' with the gap column (tools/latin10.py)"""
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import latin10
    st = latin10.ui_style(U) if ui else latin10.sys_style(G)
    return [tuple(''.join('#' if v else '.' for v in r) + '.' for r in g) for g in st.high()]


