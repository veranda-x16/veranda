#!/usr/bin/env python3
"""The shell's own tiles (Veranda Look 2, DECISIONS V77): shell/tiles.txt
-> shell/tiles.h (and a picture of them for a look).

usage: mktiles.py <tiles.txt> <out.h> [--png <out.png>]

tiles.txt (its format: tools/vpack.py read_tiles): "tile" blocks, each
with "for class <GEOS class>" (an application that carries no tile of its
own: the ports of GEOS programs) or "for <the shell's>" (folder, up,
document, card, printer, trash), its colour and 32 x 32 pixels; "mini"
blocks, 11 x 11 glyphs for the sidebar and the list's kind badges.

The header has:
  tileData[n][129]   a tile: its colour (a palette entry of Look 2), then
                     the bitmap, 4 bytes a row, bit 7 the left pixel
  tileClass[k][13]   the classes of the first k tiles (12 characters,
                     space padded, as an info block's bytes 77-88)
  T_<WHAT>           the index of the shell's own tiles
  miniData[m][22]    a glyph: 11 rows of 2 bytes (bit 15 the left pixel)
  M_<NAME>           their index
Veranda's applications carry their own tile (app.hdr "tile"); the shell
draws every tile in a rounded frame of its own (radius 4).

MIT licence (see LICENSE).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vpack  # noqa: E402

SHELLS = ['folder', 'up', 'document', 'card', 'printer', 'trash']


def build(src):
    tiles, minis = [], []
    for name, kv, rows in vpack.read_tiles(src):
        if kv['kind'] == 'mini':
            minis.append((name, rows))
            continue
        what = kv.get('for', '')
        tiles.append((name, what, vpack.tile_colour(kv.get('colour', 'chrome')), vpack.tile_bitmap(rows), rows))
    classes = [t for t in tiles if t[1].startswith('class ')]
    own = [t for t in tiles if not t[1].startswith('class ')]
    if [t[1] for t in own] != SHELLS:
        raise vpack.PackError('the shell\'s tiles, in this order: ' + ', '.join(SHELLS))
    return classes + own, len(classes), minis


def header(tiles, nclass, minis):
    o = ['/* generated by tools/mktiles.py from shell/tiles.txt: the shell\'s own',
         '   tiles (Veranda Look 2, DECISIONS V77) */',
         '#define NTILES %d' % len(tiles), '#define NCLASS %d' % nclass]
    for i, t in enumerate(tiles[nclass:]):
        o.append('#define T_%s %d' % (t[1].upper(), nclass + i))
    for i, (n, _) in enumerate(minis):
        o.append('#define M_%s %d' % (n.upper(), i))
    o.append('#ifdef TILE_DATA')
    o.append('static const char tileClass[NCLASS][13] = {')
    for t in tiles[:nclass]:
        c = t[1][6:].strip()
        if len(c) > 12:
            raise vpack.PackError('class "%s": at most 12 characters' % c)
        o.append('    "%s",     /* %s */' % (c.ljust(12), t[0]))
    o.append('};')
    o.append('static const unsigned char tileData[NTILES][129] = {')
    for name, what, col, bm, _ in tiles:
        b = bytes([col]) + bm
        o.append('    {   /* %s (%s, %s) */' % (name, what, vpack.TILE_COLOURS[col]))
        for i in range(0, 129, 16):
            o.append('        ' + ' '.join('0x%02X,' % x for x in b[i:i + 16]))
        o.append('    },')
    o.append('};')
    o.append('static const unsigned int miniData[%d][11] = {' % len(minis))
    for n, rows in minis:
        v = [int(r.replace('#', '1').replace('.', '0').ljust(16, '0'), 2) for r in rows]
        o.append('    { %s },  /* %s */' % (', '.join('0x%04X' % x for x in v), n))
    o.append('};')
    o.append('#endif')
    return '\n'.join(o) + '\n'


def png(tiles, out):
    from PIL import Image, ImageDraw
    im = Image.new('L', (len(tiles) * 40, 40), 255)
    d = ImageDraw.Draw(im)
    for i, t in enumerate(tiles):
        x = i * 40 + 4
        d.rounded_rectangle([x, 4, x + 31, 35], radius=4, outline=0)
        for y, r in enumerate(t[4]):
            for j, ch in enumerate(r):
                if ch == '#':
                    im.putpixel((x + j, 4 + y), 0)
    im.resize((im.width * 2, im.height * 2)).save(out)


def main():
    a = sys.argv[1:]
    if len(a) not in (2, 4) or (len(a) == 4 and a[2] != '--png'):
        sys.exit(__doc__)
    try:
        tiles, nclass, minis = build(a[0])
    except (vpack.PackError, OSError) as e:
        sys.exit('mktiles: %s' % e)
    open(a[1], 'w').write(header(tiles, nclass, minis))
    if len(a) == 4:
        png(tiles, a[3])


if __name__ == '__main__':
    main()
