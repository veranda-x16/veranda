def rows(art, w, h):
    lines = [ln for ln in art.strip('\n').split('\n')]
    lines = [(ln + '.' * w)[:w] for ln in lines][:h]
    while len(lines) < h:
        lines.append('.' * w)
    return lines


def bits(lines):
    out = []
    for ln in lines:
        for b in range(0, len(ln), 8):
            v = 0
            for i, c in enumerate(ln[b:b + 8]):
                if c == '#':
                    v |= 0x80 >> i
            out.append(v)
    return out


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    out = ['/* generated by tools/mkshellicons.py: the shell\'s own pictures */']
    pics = {}
    out.append('#ifdef DESK_ICONS')
    for name, art in ICONS.items():
        b = bits(rows(art, 24, 21))
        pics[name] = (24, 21)
        out.append('static const unsigned char %s[64] = {' % name)
        data = [0xBF] + b
        for i in range(0, 64, 16):
            out.append('    ' + ', '.join('0x%02X' % v for v in data[i:i + 16]) + ',')
        out.append('};')
    out.append('#else')
    for name, art in GLYPHS.items():
        b = bits(rows(art, 8, 8))
        out.append('static const unsigned char %s[9] = { 0x88, %s };' % (name, ', '.join('0x%02X' % v for v in b)))
    out.append('#endif')
    open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
    if '--png' in sys.argv:
        from PIL import Image
        im = Image.new('L', (4 * 28 + 4 * 12, 24), 255)
        x = 0
        for name, art in ICONS.items():
            for y, ln in enumerate(rows(art, 24, 21)):
                for i, c in enumerate(ln):
                    if c == '#':
                        im.putpixel((x + i, y), 0)
            x += 28
        for name, art in GLYPHS.items():
            for y, ln in enumerate(rows(art, 8, 8)):
                for i, c in enumerate(ln):
                    if c == '#':
                        im.putpixel((x + i, y), 0)
            x += 12
        im.resize((im.width * 4, im.height * 4), Image.NEAREST).save(sys.argv[sys.argv.index('--png') + 1])


if __name__ == '__main__':
    main()
