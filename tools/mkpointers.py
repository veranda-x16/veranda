def busy(f):
    """frame f of the busy pointer: a white disc in a dark ring, eight
    dots around its middle; dot f dark, the two before it grey, the rest
    light grey (one step clockwise a frame)"""
    rows = []
    c = 7.5
    for y in range(16):
        row = ''
        for x in range(16):
            r = math.hypot(x - c, y - c)
            if r > 7.6:
                v = 0
            elif r > 6.6:
                v = 1
            else:
                v = 2
                for k in range(8):
                    a = math.radians(45 * k)
                    if math.hypot(x - (c + 4.2 * math.sin(a)), y - (c - 4.2 * math.cos(a))) < 1.45:
                        age = (f - k) % 8
                        v = 1 if age == 0 else 3 if age <= 2 else 4
            row += str(v)
        rows.append(row)
    return rows


def shapes():
    """[(name, rows, hot x, hot y)] in slot order"""
    s = [('arrow', ARROW, 0, 0), ('ibeam', IBEAM, 6, 8), ('cross', CROSS, 7, 7)]
    s += [('busy%d' % f, busy(f), 7, 7) for f in range(BUSY_FRAMES)]
    return s


def packed(rows):
    out = bytearray()
    for r in rows:
        assert len(r) == 16, r
        for i in range(8):
            out.append((int(r[2 * i]) << 4) | int(r[2 * i + 1]))
    return bytes(out)


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    sh = shapes()
    o = ['; generated by tools/mkpointers.py: Veranda\'s pointer shapes (16x16, 4 bpp)',
         'PTR_SHAPES = %d' % len(sh), 'PTR_BUSY_FRAMES = %d' % BUSY_FRAMES,
         'PTR_SLOT_OFFSET = %d' % SLOT_OFFSET, '.ifdef PTR_DATA', 'PtrPics:']
    for name, rows, hx, hy in sh:
        o.append('; %s (hot spot %d, %d)' % (name, hx, hy))
        b = packed(rows)
        for i in range(0, 128, 16):
            o.append('\t.byte ' + ', '.join('$%02X' % v for v in b[i:i + 16]))
    o.append('PtrHotX:\t.byte ' + ', '.join(str(s[2]) for s in sh))
    o.append('PtrHotY:\t.byte ' + ', '.join(str(s[3]) for s in sh))
    o.append('PtrPal:\t.word ' + ', '.join('$%04X' % p for p in PAL))
    o.append('.endif')
    open(sys.argv[1], 'w').write('\n'.join(o) + '\n')
    if '--png' in sys.argv:
        from PIL import Image
        cols = {0: (0, 160, 160), 1: (0, 0, 0), 2: (255, 255, 255), 3: (136, 136, 136), 4: (204, 204, 204)}
        img = Image.new('RGB', (len(sh) * 20 * 4, 20 * 4), (0, 160, 160))
        for i, (_, rows, _, _) in enumerate(sh):
            for y, r in enumerate(rows):
                for x, ch in enumerate(r):
                    for a in range(4):
                        for b in range(4):
                            img.putpixel(((i * 20 + 2 + x) * 4 + a, (2 + y) * 4 + b), cols[int(ch)])
        img.save(sys.argv[sys.argv.index('--png') + 1])


if __name__ == '__main__':
    main()
