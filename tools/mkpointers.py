#!/usr/bin/env python3
"""Veranda's pointer shapes (SetPointer, DECISIONS V51): 16x16 sprites at
4 bpp in sprite palette offset 1 (entries 16-31): 0 transparent, 1 the
outline (entry 17: Look 2's dark slate $112, DECISIONS V74), 2 white (18),
3 grey (19), 4 light grey (20).

usage: mkpointers.py <out.inc> [--png out.png]

Writes ca65 source: PtrPics (the shapes in slot order, 128 bytes each:
the arrow, the I-beam, the crosshair, then the busy pointer's BUSY_FRAMES
frames), PtrHotX and PtrHotY (each shape's hot spot), PtrPal (entries
17-20, $0RGB). The gates import shapes() to check sprite 0's slot in a
VRAM dump. The pictures are Veranda's own (MIT).
"""
import math
import sys

BUSY_FRAMES = 8
SLOT_OFFSET = 512               # in sprite 0's 2 KB slot: after a 32x32 DrawSprite picture
PAL = [0x112, 0xFFF, 0x889, 0xCCD]      # entries 17-20 (V74: Look 2's slate greys)

