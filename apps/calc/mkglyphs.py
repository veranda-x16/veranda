def rows(pic):
    r = [l for l in pic.strip('\n').split('\n')]
    w = len(r[0])
    assert all(len(l) == w for l in r), pic
    assert w <= 16
    return w, [sum(1 << (15 - i) for i, ch in enumerate(l) if ch == '#') for l in r]


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'glyphs.h')
    L = ['/* the Calculator\'s glyphs: written by apps/calc/mkglyphs.py (do not edit) */',
         '#define BIG_H 20',
         '#define BIG_CHARS "%s"' % BIG_ORDER,
         'static const unsigned char big_w[%d] = { %s };' % (len(BIG_ORDER), ', '.join(
             str(rows(BIG[c])[0]) for c in BIG_ORDER)),
         'static const unsigned int big_rows[%d][BIG_H] = {' % len(BIG_ORDER)]
    for c in BIG_ORDER:
        w, r = rows(BIG[c])
        assert len(r) == 20, c
        L.append('    { %s },  /* %s */' % (', '.join('0x%04X' % v for v in r), c))
    L.append('};')
    for i, (name, top, pic) in enumerate(SMALL):
        L.append('#define %s 0x%02X' % (name, 0x80 + i))
    L.append('#define G_COUNT %d' % len(SMALL))
    L.append('static const unsigned char small_w[G_COUNT] = { %s };' % ', '.join(str(rows(p)[0]) for _, _, p in SMALL))
    L.append('static const signed char small_top[G_COUNT] = { %s };' % ', '.join(str(t) for _, t, _ in SMALL))
    L.append('static const unsigned char small_h[G_COUNT] = { %s };' % ', '.join(str(len(rows(p)[1])) for _, _, p in SMALL))
    flat, at = [], []
    for _, _, p in SMALL:
        at.append(len(flat))
        flat += rows(p)[1]
    L.append('static const unsigned char small_at[G_COUNT] = { %s };' % ', '.join(map(str, at)))
    L.append('static const unsigned int small_rows[%d] = {' % len(flat))
    for i in range(0, len(flat), 8):
        L.append('    ' + ', '.join('0x%04X' % v for v in flat[i:i + 8]) + ',')
    L.append('};')
    with open(out, 'w') as o:
        o.write('\n'.join(L) + '\n')


if __name__ == '__main__':
    main()
